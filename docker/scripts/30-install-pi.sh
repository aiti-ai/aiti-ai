#!/usr/bin/env bash
# 30-install-pi.sh — pi engine + pi-side extension packages (aiti-docker-image-plan §2.1.2/§8.3)
# Usage: 30-install-pi.sh <NPM_MIRROR>
# Installs: global pi CLI (@earendil-works/pi-coding-agent) + /opt/aiti/agent/settings.json packages
set -euo pipefail
NPM_MIRROR="${1:-https://registry.npmmirror.com}"
AGENT_DIR=/opt/aiti/agent
mkdir -p "$AGENT_DIR"

npm config set registry "$NPM_MIRROR"
# pi engine global install (same packages pi-web depends on; the in-process SDK uses /opt/aiti/app/node_modules versions)
npm install -g --no-audit --no-fund @earendil-works/pi-coding-agent@0.84.3

# settings.json (the six packages) is now generated by entrypoint.sh at first startup — supporting ~/.pi mounts that
# inherit host config (jq merge: user keys win + packages union, 2026-09-10); no longer pre-written at build time.
