#!/usr/bin/env node
// gen-deps.mjs — S3 extension dependency matrix generator (aiti-docker-image-plan §7.2)
// Scans every extension's package.json `aiti` metadata block → aggregates the full-layer system dependency list
// (the generated source for Dockerfile.full's extra layers; the §2.2 hand-written list is demoted to a verification baseline).
// Missing metadata = declaring "zero system dependencies".
//
// Usage: node docker/scripts/gen-deps.mjs [pi-web-ext dir]
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2] ?? new URL("../../pi-web-ext/", import.meta.url).pathname;
const entries = readdirSync(root, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
// Count = directories that have a package.json (infrastructure dirs like _shared/templates naturally lack one and are excluded;
// correct for any custom scan dir too — the original hardcoded -5 went negative on custom dirs)
const candidates = entries.filter((name) => existsSync(join(root, name, "package.json")));

const byPlatform = { "linux-apt": new Map(), windows: new Map(), darwin: new Map() };
const services = [];
const tiers = { core: [], full: [] };
let declared = 0;

for (const name of entries) {
  const pkgPath = join(root, name, "package.json");
  if (!existsSync(pkgPath)) continue;
  let pkg;
  try { pkg = JSON.parse(readFileSync(pkgPath, "utf8")); } catch { continue; }
  const meta = pkg.aiti;
  if (!meta) continue; // missing = zero system dependencies (S3 rule)
  declared++;
  (tiers[meta.tier ?? "core"] ??= []).push(name);
  for (const [platform, deps] of Object.entries(meta.systemDeps ?? {})) {
    const bucket = byPlatform[platform];
    if (!bucket) continue;
    const list = Array.isArray(deps) ? deps : depsList(deps); // windows variant: [{winget,choco}] or [str]
    for (const d of list) {
      const key = typeof d === "string" ? d : d.winget ?? d.choco ?? JSON.stringify(d);
      if (!bucket.has(key)) bucket.set(key, []);
      bucket.get(key).push(name);
    }
  }
  for (const s of meta.services ?? []) services.push({ ext: name, ...s });
}

function depsList(deps) {
  if (Array.isArray(deps)) return deps;
  return Object.entries(deps).map(([k, v]) => ({ [k]: v }));
}

console.log(`# Extension dependency matrix (generated by gen-deps @ ${new Date().toISOString().slice(0, 10)})`);
console.log(`# Extensions declaring aiti metadata: ${declared}/${candidates.length} (missing = zero deps)`);
for (const [tier, list] of Object.entries(tiers)) {
  console.log(`\n## tier=${tier}（${list.length}）\n${list.sort().map((n) => `- ${n}`).join("\n")}`);
}
for (const [platform, bucket] of Object.entries(byPlatform)) {
  if (bucket.size === 0) continue;
  console.log(`\n## systemDeps.${platform}`);
  for (const [dep, exts] of [...bucket].sort()) console.log(`- ${dep}  ← ${exts.join(", ")}`);
}
if (services.length) {
  console.log("\n## services (S5 phases declaration source)");
  for (const s of services) console.log(`- [${s.ext}] ${s.name} :${s.port ?? "-"} phase=${s.phase} cmd=${s.cmd}`);
}
