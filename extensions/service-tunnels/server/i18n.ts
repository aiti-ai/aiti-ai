// ── 单源合并（方案 §3.3）─────────────────────────────────────────────────
// 新功能域文案（ui.ddns.* / ui.portmap.* / ui.ipv6.* / ui.doctor.*）只在库
// CATALOG 写一遍，此处按域过滤合并进 I18N——构建时随 client bundle 内联
// （host-shim translate 用），服务端运行时同样生效（ctx.t）。库版本过旧
// （无对应键）→ 只缺新键回退 key，不阻塞。
/** 合并进扩展表的库键域（前缀匹配；与扩展 services.* 天然无冲突）。 */
const LIB_KEY_PREFIXES = ["ui.ddns.", "ui.portmap.", "ui.ipv6.", "ui.doctor.", "ui.ports.", "ui.detail."];
/** 库 Lang → 扩展 locale 键映射（扩展用 "zh-CN"）。 */
const LOCALE_MAP: Record<string, string> = { en: "en", zh: "zh-CN" };

function pickLibKeys(table: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(table)) {
    if (LIB_KEY_PREFIXES.some((p) => k.startsWith(p))) out[k] = v;
  }
  return out;
}

/** 库键合并（惰性）：由 server.startup 调用；客户端 bundle 走 client/lib-i18n.ts 构建期静态合并。
 *  动态 import + try/catch：宿主进程 exports 解析缓存旧视图（未重启）下不炸加载。 */
export async function mergeLibCatalog(): Promise<void> {
  try {
    const { CATALOG } = await import("service-tunnels/i18n");
    for (const [libLang, locale] of Object.entries(LOCALE_MAP)) {
      I18N[locale] = { ...pickLibKeys((CATALOG as Record<string, Record<string, string>>)[libLang] ?? {}), ...I18N[locale] };
    }
  } catch { /* 库过旧/解析缓存旧视图 → 缺新键回退裸键 */ }
}

