export function panelDict(locale) {
  const l = String(locale || "");
  if (/^zh-(tw|hk)|^zh_H(TW|HK)/i.test(l)) return DICT.tw;
  if (/^zh/i.test(l)) return DICT.cn;
  return DICT.en;
}

export function makeT(locale) {
  const d = panelDict(locale);
  return (key, ...args) => {
    const v = d[key];
    return typeof v === "function" ? v(...args) : (v ?? key);
  };
}
