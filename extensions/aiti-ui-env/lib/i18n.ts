const derivedZh: Record<string, string> = {};
for (const key of Object.keys(en)) if (CJK.test(key)) derivedZh[key] = key;

/** Locale table exposed as the extension manifest `ui.i18n`. */
export const uiI18n: Record<string, Record<string, string>> = {
  en,
  "zh-CN": { ...derivedZh, ...zhCN },
};

/** Maps any UI locale (en / zh-CN / zh-TW / zh-Hans …) onto a table we ship. */
export function normalizeLocale(value?: string | null): UiLocale {
  const s = String(value ?? "").trim().toLowerCase();
  return s.startsWith("zh") ? "zh-CN" : "en";
}

/** Server-side translate: locale → text with `{name}` interpolation; unknown key degrades to the key. */
export function tr(locale: string | undefined | null, key: string, params?: Record<string, string | number>): string {
  const table = uiI18n[normalizeLocale(locale)];
  let msg = table[key] ?? en[key] ?? key;
  if (params) {
    msg = msg.replace(/\{([\w.-]+)\}/g, (token, name: string) => (params[name] === undefined ? token : String(params[name])));
  }
  return msg;
}

/** Like tr(), but falls back to a caller-supplied default instead of the key when untranslated. */
export function trOr(locale: string | undefined | null, key: string, fallback: string, params?: Record<string, string | number>): string {
  if (uiI18n[normalizeLocale(locale)][key] === undefined && en[key] === undefined) return fallback;
  return tr(locale, key, params);
}

/** Minimal shape of a probe result that carries a failure (see ProbeInfo in lib/env.ts). */
type ProbeFailInfo = { error?: string; errorCode?: string; errorParams?: Record<string, string | number> };

/** Marks a probe result as failed with a semantic `srv.probe.*` key (bare code is prefixed automatically):
 *  keeps the stable code, the interpolation params, and the zh-CN fallback text on the info object; returns info. */
export function probeFail<T extends ProbeFailInfo>(info: T, key: string, params?: Record<string, string | number>): T {
  const full = key.startsWith("srv.probe.") ? key : "srv.probe." + key;
  info.errorCode = full;
  if (params) info.errorParams = params;
  info.error = tr("zh-CN", full, params);
  return info;
}

/** Localized failure text for a probe result; undefined when the probe did not fail. */
export function probeErrorText(locale: string | undefined | null, info: ProbeFailInfo | null | undefined): string | undefined {
  if (!info) return undefined;
  if (info.errorCode) return tr(locale, info.errorCode, info.errorParams);
  return info.error || undefined;
}
